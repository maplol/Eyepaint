export type OnboardingStep = number

const KEY = 'eyepaint-onboarding-done-v1'

export function isOnboardingDone() {
  try {
    return localStorage.getItem(KEY) === '1'
  } catch {
    return true
  }
}

export function markOnboardingDone() {
  localStorage.setItem(KEY, '1')
}

